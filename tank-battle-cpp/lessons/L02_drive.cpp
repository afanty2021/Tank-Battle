// ============================================================
//  第 2 课 · 用 W A S D 指挥坦克, 不许开出场地
//
//  今天的三个新积木:
//    1. if (条件) { ... }        —— 就是【如果...那么】
//    2. key_pressed("W")         —— 就是【按下 W 键?】
//    3. 比较运算 > 和 <          —— 判断有没有出界
//
//  编译方法: 双击 lessons\compile.bat L02 , 然后双击 L02.exe
//  (按 Esc 或点 X 退出)
// ============================================================
#include "scratch_like.hpp"

int main() {
    open_window();

    float x = 0;                      // 出发位置: 场地中下方
    float y = -150;
    float dir = 0;                    // 0=朝上 90=朝右 180=朝下 270=朝左(同 Scratch)

    while (window_open()) {           // 【重复执行】
        // ---- 第 1 步: 听按键, 谁按着就往谁那边走 ----
        if (key_pressed("W")) {       // 【当按下 W 键】【将 y 坐标增加 5】
            y = y + 5;
            dir = 0;                  // 车头转向移动方向(和正式版一样)
        }
        if (key_pressed("S")) {
            y = y - 5;
            dir = 180;
        }
        if (key_pressed("A")) {
            x = x - 5;
            dir = 270;
        }
        if (key_pressed("D")) {
            x = x + 5;
            dir = 90;
        }

        // ---- 第 2 步: 不许出界(活动范围抄自正式版 Game.hpp) ----
        if (x > 205)  x = 205;        // 【如果 x > 205 那么】设 x 为 205
        if (x < -211) x = -211;
        if (y > 150)  y = 150;
        if (y < -154) y = -154;

        // ---- 第 3 步: 画出来 ----
        clear();
        draw_background();
        draw_tank(x, y, dir);
        display();
    }
    return 0;
}

