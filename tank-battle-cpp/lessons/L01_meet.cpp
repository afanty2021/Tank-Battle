//
//  今天要认识的三个新朋友:
//    1. while 循环   —— 就是 Scratch 里的【重复执行】
//    2. 变量 x 和 y  —— 就是 Scratch 舞台的横纵坐标(中心是 0)
//    3. 编译         —— 把 .cpp 文本变成能双击运行的 .exe
//
//  编译: 双击 lessons\compile.bat 输入课号 1 回车,
//        然后双击上一层 tank-battle-cpp\ 文件夹里的 L01.exe
// ============================================================
#include "scratch_like.hpp"

int main() {
    open_window();                    // 【打开窗口】960x720, 和正式版一样大

    // 坦克的位置。变量就像 Scratch 里的变量积木, 里面装着一个数。
    // 舞台中心是 (0,0), x 向右为正, y 向上为正(和 Scratch 一模一样!)
    float x = 0;
    float y = -100;

    while (window_open()) {           // 【重复执行】直到关掉窗口
        clear();                      // 擦掉上一帧的画面
        draw_background();            // 【背景】画出战场
        draw_tank(x, y, 0);           // 在 (x, y) 画坦克, 方向 0 = 朝上

        y = y + 0.5f;                 // 【将 y 坐标增加 0.5】每帧上移一点

        display();                    // 把这一帧显示出来(每秒 30 帧)
    }
    return 0;
}

