// ============================================================
//  第 3 课 · 拦不住的敌人: 会反弹的斜线运动
//
//  今天的两个新知识:
//    1. 取反  -vx      —— 把一个数变成相反数(正变负, 负变正)
//    2. 两个速度 vx, vy —— 斜着飞 = 横竖两个方向各有一个速度
//
//  Scratch 里你拖过【碰到边缘就反弹】这块积木, 它内部干的就是这件事:
//  碰到左/右边缘, 把横向速度取反; 碰到上/下边缘, 把纵向速度取反。
//  今天我们自己把这块积木造出来!
//
//  编译方法: 双击 lessons\compile.bat L03 , 然后双击 L03.exe
// ============================================================
#include "scratch_like.hpp"

int main() {
    open_window();

    float x = 0, y = 0;      // 敌人的位置
    float vx = 3;            // 每帧向右走 3(v 城 velocity, 速度)
    float vy = 2;            // 每帧向上走 2

    while (window_open()) {  // 【重复执行】
        // ---- 1. 先移动 ----
        x = x + vx;
        y = y + vy;

        // ---- 2. 碰到边缘就把那个方向的速度取反(反弹!) ----
        if (x > 230)  vx = -vx;    // 碰到右边: 向右的速度变向左
        if (x < -230) vx = -vx;    // 碰到左边: 向左的速度变向右
        if (y > 170)  vy = -vy;    // 碰到上边: 向上变向下
        if (y < -170) vy = -vy;    // 碰到下边: 向下变向上

        // ---- 3. 画 ----
        clear();
        draw_background();
        draw_enemy(x, y, 90);      // 90 = 朝右(其实它在斜着飞, 转向练习见下面)
        display();
    }
    return 0;
}

