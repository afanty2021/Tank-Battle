// ============================================================
//  第 5 课 · 发射导弹! 数组(vector)登场
//
//  Scratch 里你用过【克隆】: 按一下空格, 造一个新的导弹克隆体。
//  C++ 里干这件事的是 数组(vector)——一列带编号的格子,
//  我们用两列格子记下每颗导弹的位置: mx[0], my[0] 是第 0 颗,
//  mx[1], my[1] 是第 1 颗……
//
//  三个新招:
//    mx.push_back(v)   往数组尾巴添一格(= 造一个克隆体)
//    mx[i]             取第 i 格(编号从 0 开始!)
//    mx.erase(...)     删掉第 i 格(= 删除克隆体)
//
//  编译: 双击 lessons\compile.bat 输入课号 5 回车,
//        然后双击上一层 tank-battle-cpp\ 文件夹里的 L05.exe
// ============================================================
#include "scratch_like.hpp"
#include <vector>              // 用数组要先"借"这个工具箱

int main() {
    open_window();

    // 坦克(沿用第 2 课的驾驶, 这次只保留左右)
    float x = 0, y = -150;

    std::vector<float> mx;     // 所有导弹的 x ——列账本
    std::vector<float> my;     // 所有导弹的 y ——列账本
    int fire_wait = 0;         // 冷却: 还要等多少帧才能再发(0=可以发)

    while (window_open()) {
        // ---- 1. 驾驶 ----
        if (key_pressed("A")) x = x - 5;
        if (key_pressed("D")) x = x + 5;
        if (x > 205)  x = 205;    // 活动范围与第 2 课/正式版一致
        if (x < -211) x = -211;    // (两边不对称是原版积木就这么写的)

        // ---- 2. 发射: 按住空格连发, 每 10 帧一发(约 1/3 秒) ----
        if (fire_wait > 0) fire_wait = fire_wait - 1;   // 倒计时
        if (key_pressed("SPACE") && fire_wait == 0) {
            mx.push_back(x);              // 账本添一行: 新导弹的 x
            my.push_back(y + 20);         //            和 y(从炮口出发)
            fire_wait = 10;               // 重新上冷却
        }

        // ---- 3. 每颗导弹往上飞(这里只算位置, 还不能画!) ----
        for (int i = 0; i < (int)mx.size(); i++) {   // (int)只是一种写法, 照抄
            my[i] = my[i] + 10;
        }

        // ---- 4. 飞出屏幕的导弹删掉 ----
        // 必须从后往前删(i 从大到小): 删掉一颗后, 后面的会顶上来补位;
        // 要是从前往后删, 补位的这颗恰好被 i++ 跳过——永远留在场上
        for (int i = (int)mx.size() - 1; i >= 0; i--) {
            if (my[i] > 200) {
                mx.erase(mx.begin() + i); // begin()+i = 第 i 格的位置
                my.erase(my.begin() + i);
            }
        }

        // ---- 5. 画。顺序是铁律: 先 clear, 再画所有东西, 最后 display ----
        clear();
        draw_background();
        draw_tank(x, y, 0);
        for (int i = 0; i < (int)mx.size(); i++)
            draw_missile(mx[i], my[i], 0);  // 每颗导弹都要画
        display();
    }
    return 0;
}

